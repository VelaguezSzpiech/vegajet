// EVICT prefix-depth controller: an advisory draft-prefix length for a target verifier whose cost grows with
// the union of routed MoE experts.  This is the small, replayable interface that sits in front of a speculative
// decoder; the full expert-union planner lives in core/evict_controller.hpp.
//
// Call protocol (one decode step):
//   1. The caller has `available_draft` draft tokens from its drafter and the measured distinct
//      (layer, expert) key count from the last completed target verifier pass:
//          k = depth.choose(available_draft, unique_experts);
//   2. The caller verifies the first min(k, available_draft) drafts against the target model.  The controller
//      NEVER supplies, commits or rewrites a token.  The target verifier is the only authority for the accepted
//      prefix and for the correction/bonus token that follows it.
//   3. Once the target decision is known:
//          depth.observe(attempted, accepted);        // accepted = target-accepted prefix length in [0, attempted]
//   4. When choose() returns 0, the caller runs an ordinary single-token target decode.  That consumes one real
//      decode step (unless the request already ended) and must still emit the target token.  A zero proposal is a
//      cost decision, not a request to stall; the controller is not on the commit path.
//
// `unique_experts` is the exact number of distinct (layer, routed-expert) keys observed in the last COMPLETED
// target verifier pass, supplied by `RouteUnion`/`RouteUnionFeedback` (core/route_union.hpp).  It is a lagged
// cost-feedback signal, not a prediction of the current candidate, and it is never a per-layer average or a
// per-token count.  `0` means "unknown / no routing pressure": cold start, deferred or unavailable readback, a
// zero-token step, or an already-consumed one-shot value.  Callers must pass 0 in those cases; they must not
// substitute top_k * layers, a uniform-routing expectation, or any other metadata for a measured count.  The
// controller discounts the learned per-position acceptance when the measured union is large relative to
// `experts_per_depth * prefix_capacity`, then keeps the deepest draft position whose probability of being reached
// is still at least `min_survival`.
//
// Verified acceptance history: `observe()` treats one verify pass as a geometric chain and updates an EWMA of the
// per-position acceptance probability using the standard `accepted / (accepted + 1)` estimator (1.0 when the whole
// draft was accepted).  Two consecutive all-reject passes put the controller into a target-only state.  Target-only
// steps are cheap and make progress, but they cannot reveal that the workload has changed (for example prose drying
// up and code becoming predictable again), so after `probe_after` target-only proposals the controller proposes a
// one-token probe.  The target verifier remains free to reject it; a rejected probe restarts the cooldown and an
// accepted probe lets the depth estimate climb again.
//
// Claude replay semantics (the recorded trace must keep these columns separate):
//   * proposed depth     - the value choose() returned for this step
//   * unique experts     - the value passed to choose()
//   * verified prefix    - how many drafts the TARGET accepted (0..proposed), never the controller's opinion
//   * correction token   - the target token after that prefix (the bonus token at depth > 0, the only token at 0)
//   * emitted tokens     - target-accepted drafts followed by the correction token; never generated by the controller
// Replay cold start (no observations yet), first-token rejection (accepted == 0 with attempted > 0), full acceptance
// (accepted == attempted), and code/prose regime changes.  In every case the emitted-token count must be
// `verified_prefix + 1` at nonzero depth and exactly 1 at depth zero; no step may emit zero tokens before EOS.
//
// Not thread-safe: use one instance per decode stream (or guard it externally).
#pragma once

#include <cstdint>

namespace vegajet {

struct EvictDepthConfig {
    double prior_accept = 0.75;     // cold-start P(next draft position accepted); no history exists yet
    double min_survival = 0.05;     // deepest proposed position must have at least this chance of being reached
    double ewma = 0.25;             // smoothing of the verified acceptance history
    uint32_t experts_per_depth = 8; // unique (layer, expert) pairs allowed per draft slot before discounting acceptance
    uint32_t hard_zero_streak = 2;  // consecutive all-reject verifies before switching to target-only steps
    uint32_t probe_after = 2;       // target-only proposals before a one-token probe is attempted
    uint32_t probe_depth = 1;       // draft length of that probe (clamped to the proposal capacity)
};

struct EvictDepthChoice {
    uint32_t depth = 0;             // the advisory prefix length returned to the caller
    uint32_t cap = 0;               // min(available_draft, max_depth) for this proposal
    uint32_t acceptance_limit = 0;  // depth implied by acceptance history alone (before expert discounting)
    uint64_t unique_experts = 0;    // measured union passed to choose(); 0 = unknown, never an estimate
    double acceptance = 0.0;        // EWMA P(next draft position accepted)
    double expert_pressure = 1.0;   // >= 1: discount applied to acceptance for this unique-expert count
    bool target_only = false;       // true: caller must run one ordinary target decode
    bool probing = false;           // true: this nonzero proposal is a post-cooldown probe
    bool limited_by_experts = false;// true: expert pressure shortened the acceptance-only depth
};

class EvictDepth {
public:
    explicit EvictDepth(uint32_t max_depth, EvictDepthConfig cfg = EvictDepthConfig{});

    // Advisory prefix length in [0, min(available_draft, max_depth)].  0 means "target-only this step".
    // Call exactly once per decode step; the internal probe cooldown counts these calls.
    uint32_t choose(uint32_t available_draft, uint64_t unique_experts) noexcept;

    // The target verifier's result: `attempted` drafts were checked, `accepted` formed the accepted prefix.
    // `attempted == 0` is ignored (nothing was verified).  `accepted` is clamped to `attempted`.
    void observe(uint32_t attempted, uint32_t accepted) noexcept;

    // Forgets the verified history and returns to the cold-start state; config and max_depth are preserved.
    void reset() noexcept;

    uint32_t max_depth() const noexcept { return max_depth_; }
    const EvictDepthConfig& config() const noexcept { return cfg_; }
    double acceptance() const noexcept { return acceptance_; }
    uint32_t observations() const noexcept { return observations_; }
    uint32_t zero_streak() const noexcept { return zero_streak_; }
    // The complete decision record of the most recent choose() call (also useful as a trace row).
    const EvictDepthChoice& last_choice() const noexcept { return last_; }

private:
    uint32_t depth_for(double acceptance) const noexcept;
    double expert_pressure(uint64_t unique_experts, uint32_t cap) const noexcept;

    uint32_t max_depth_ = 0;
    EvictDepthConfig cfg_;
    double acceptance_ = 0.0;   // EWMA of the verified per-position acceptance
    uint32_t observations_ = 0;
    uint32_t zero_streak_ = 0;  // consecutive verifies with accepted == 0
    uint32_t quiet_steps_ = 0;  // target-only proposals since the last observe()/probe
    EvictDepthChoice last_;
};

} // namespace vegajet
